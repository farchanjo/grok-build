WORD = re.compile(r"[a-z0-9_]{3,}")


def tokens(text: str) -> set[str]:
    return set(WORD.findall(text.lower()))


def keyword_rank(query: str, corpus: list[dict[str, str]]) -> list[str]:
    qt = tokens(query)
    scored = [(len(qt & tokens(c["text"])) / (len(qt) or 1), c["id"]) for c in corpus]
    return [cid for _, cid in sorted(scored, key=lambda kv: -kv[0])]


@dataclass
class Row:
    query: str
    gold: str
    baseline_top1: str
    jev_top1: str | None = None
    jev_correct: bool | None = None
    baseline_correct: bool | None = None
    latency_ms: float = 0.0
    input_tokens: int = 0
    error: str = ""
    extra: dict[str, Any] = field(default_factory=dict)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--transport", default="native")
    args = parser.parse_args()
    OUT.mkdir(exist_ok=True)

    rows: list[Row | None] = [None] * len(QUERIES)

    def one(index: int) -> tuple[int, Row]:
        case = QUERIES[index]
        base = keyword_rank(case["q"], CORPUS)
        row = Row(
            query=case["q"],
            gold=case["gold"],
            baseline_top1=base[0],
            baseline_correct=base[0] == case["gold"],
        )
        state = {"workspace_path": WORKSPACE_PATH, "query": case["q"]}
        questions = {
            f"cand::{c['id']}": primitives.noul(
                f"{QUESTION}\n\nChunk (scope: {c['scope']}): {c['text']}",
                true=CRITERIA_TRUE,
                false=CRITERIA_FALSE,
            )
            for c in CORPUS
        }
        try:
            response = client.ask(state, questions)
        except transports.TransportError as error:
            row.error = str(error)
            return index, row
        row.latency_ms = response.latency_ms
        row.input_tokens = response.input_tokens
        scored = sorted(
            ((response.noul(f"cand::{c['id']}"), c["id"]) for c in CORPUS), key=lambda kv: -kv[0]
        )
        row.jev_top1 = scored[0][1]
        row.jev_correct = row.jev_top1 == case["gold"]
        row.extra["top3"] = [cid for _, cid in scored[:3]]
        row.extra["gold_score"] = next(s for s, cid in scored if cid == case["gold"])
        return index, row

    with transports.Client.build(args.transport, timeout_s=60.0) as client:
        with ThreadPoolExecutor(max_workers=WORKERS) as pool:
            for index, row in pool.map(one, range(len(QUERIES))):
                rows[index] = row
    result = [r for r in rows if r is not None]

    console.rule(f"memory rerank — {args.transport}")
    table = Table()
    for column in ("metric", "keyword baseline", "jev rerank"):
        table.add_column(column)
    b = sum(1 for r in result if r.baseline_correct)
    j = sum(1 for r in result if r.jev_correct)
    table.add_row("top-1 correct", f"{b}/{len(result)}", f"{j}/{len(result)}")
    table.add_row("gold in top-3", "-", f"{sum(1 for r in result if r.gold in r.extra.get('top3', []))}/{len(result)}")
    table.add_row("p50 ms", "-", f"{statistics.median([r.latency_ms for r in result]):.0f}")
    console.print(table)

    console.print("\nper query:")
    for row in result:
        mark = "[green]OK[/green]" if row.jev_correct else "[red]ERR[/red]"
        base_mark = "ok" if row.baseline_correct else "err"
        console.print(
            f"  {mark} base={base_mark} gold={row.gold:<10} jev={row.jev_top1:<10} "
            f"gold_score={row.extra.get('gold_score', 0):.2f}  {row.query}"
        )

    raw = OUT / f"results-memory-rerank-{args.transport}.jsonl"
    with raw.open("w", encoding="utf-8") as handle:
        for row in result:
            handle.write(json.dumps(asdict(row), ensure_ascii=False) + "\n")
    console.print(f"\n-> {raw.relative_to(ROOT)}")


if __name__ == "__main__":
    main()