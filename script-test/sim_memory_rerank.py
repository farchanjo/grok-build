"""Memory retrieval rerank simulation.

The leak found on disk: the global `MEMORY.md` is indexed into every workspace at
weight 1.0, and the search tool has no scope parameter. This asks whether a
rerank fixes it — and specifically whether a rerank that knows the workspace
prefers local memory when the query is local, without losing global recall.

Baseline is keyword overlap, standing in for the BM25/FTS half of the real
hybrid search. Jev asks one `noul` per candidate, in isolation, and the code
sorts by it. Corpus is the profile's three real global memories plus workspace
and session chunks for this repository.

    python sim_memory_rerank.py --transport native
"""

