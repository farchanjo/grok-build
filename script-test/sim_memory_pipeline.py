"""End-to-end memory pipeline: today's behaviour vs today plus Jev, same events.

The stages a memory system needs, and what each does today:

| stage | today | with Jev |
| --- | --- | --- |
| capture / admission | nothing is gated, everything is written | one gate, index in state |
| scope routing | everything drifts to global | routed workspace / global |
| dedup at write | none, duplicates pile up | checked against the store |
| retrieval | FTS + dense + RRF | same, unchanged |
| rerank | the profile's `reranker_models` is empty | Jev reranks the shortlist |

Nothing is removed: the retrieval half is byte-identical in both arms, and the
only difference is what got admitted, where it landed, and whether the shortlist
is reranked.

The event stream is 48 notes from a session working in this repository, mixed
with notes about other projects and with noise. Twelve later queries then ask
the store for things, from this workspace. Metrics are end-to-end: what the store
kept, where it filed it, and what the queries get back.

    python sim_memory_pipeline.py --transport native
"""

