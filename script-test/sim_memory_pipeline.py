# ── retrieval helpers (identical in both arms) ─────────────────────────────

def embed_key() -> str:
    for path in ("~/.grokdev/auth.json", "~/.grok/auth.json"):
        p = Path(path).expanduser()
        if not p.is_file():
            continue
        store = json.loads(p.read_text(encoding="utf-8"))
        for scope in ("openai_compatible::prime-embeddings::api_key", "openrouter::api_key"):
            value = store.get(scope)
            if isinstance(value, dict) and value.get("key"):
                return value["key"]
            if isinstance(value, str) and value:
                return value
    raise RuntimeError("no embedding credential")


def cached(texts: list[str], key: str, namespace: str) -> list[list[float]]:
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.is_file() else {}
    missing = [t for t in texts if f"{namespace}:{hashlib.sha1(t.encode()).hexdigest()}" not in cache]
    if missing:
        with httpx.Client(timeout=120.0) as http:
            r = http.post(
                EMBED_URL,
                headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
                json={"model": EMBED_MODEL, "input": missing},
            )
            r.raise_for_status()
            for text, item in zip(missing, r.json()["data"]):
                cache[f"{namespace}:{hashlib.sha1(text.encode()).hexdigest()}"] = item["embedding"]
        OUT.mkdir(exist_ok=True)
        CACHE.write_text(json.dumps(cache), encoding="utf-8")
    return [cache[f"{namespace}:{hashlib.sha1(t.encode()).hexdigest()}"] for t in texts]


def cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    return dot / ((math.sqrt(sum(x * x for x in a)) or 1.0) * (math.sqrt(sum(y * y for y in b)) or 1.0))


def bm25(texts: list[str], query: str, limit: int) -> list[int]:
    db = sqlite3.connect(":memory:")
    db.execute("CREATE VIRTUAL TABLE m USING fts5(t)")
    db.executemany("INSERT INTO m (t) VALUES (?)", [(t,) for t in texts])
    terms = " OR ".join(re.findall(r"[A-Za-z0-9_]{3,}", query.lower()) or ["a"])
    rows = db.execute("SELECT rowid FROM m WHERE m MATCH ? ORDER BY bm25(m) LIMIT ?", (terms, limit)).fetchall()
    db.close()
    # FTS5 rowids are 1-based; the store is a plain list.
    return [r[0] - 1 for r in rows]


def retrieve(store: list[str], vectors: list[list[float]], query: str, qvec: list[float], limit: int) -> list[int]:
    """FTS + dense + weighted RRF — the half that never changes."""
    lexical = bm25(store, query, limit)
    dense = [i for _, i in sorted(((cosine(qvec, v), i) for i, v in enumerate(vectors)), key=lambda kv: -kv[0])[:limit]]
    scores: dict[int, float] = {}
    for ranking in (lexical, dense):
        for position, index in enumerate(ranking, start=1):
            scores[index] = scores.get(index, 0.0) + 1.0 / (RRF_K + position)
    return [i for i, _ in sorted(scores.items(), key=lambda kv: -kv[1])[:limit]]


# ── the two pipelines ──────────────────────────────────────────────────────

@dataclass
class Result:
    arm: str
    stored: int = 0
    kept_right: int = 0
    dropped_wrong: int = 0
    duplicates_stored: int = 0
    dupes_caught: int = 0
    noise_slipped: int = 0
    scope_confusions: dict = field(default_factory=dict)
    scope_right: int = 0
    scope_wrong: int = 0
    top1: int = 0
    top1_no_rerank: int = 0
    in_top10: int = 0
    pollution: int = 0
    queries: int = 0
    latency_ms: float = 0.0
    tokens: int = 0
    detail: list[dict[str, Any]] = field(default_factory=list)


def run_jev_stages(client: transports.Client) -> tuple[list[Event], Result, list[str]]:
    """Admission, dedup and scope routing, all with the store in the state.

    Accounting is explicit per event so a dropped restatement is never counted
    as a loss, and a dropped valuable note never hides inside a dupe count.
    """
    result = Result("today + jev")
    admitted: list[Event] = []
    store_texts: list[str] = []

    for event in EVENTS:
        state: dict[str, Any] = {
            "candidate_note": event.text,
            "workspace_path": WORKSPACE_PATH,
            "already_in_memory": "\n".join(f"- {t}" for t in store_texts) or "(empty)",
        }
        response = client.ask(
            state,
            {
                "worth": primitives.noul(GATE_QUESTION, true=GATE_TRUE, false=GATE_FALSE),
                "covered": primitives.noul(COVERED_QUESTION),
            },
        )
        result.tokens += response.input_tokens
        result.latency_ms += response.latency_ms
        worth = response.noul("worth")
        covered = response.noul("covered")

        if covered >= COVERED_THRESHOLD:
            # A restatement being refused is the win this stage exists for.
            if event.dupe:
                result.dupes_caught += 1
            elif event.keep:
                result.dropped_wrong += 1
            else:
                result.kept_right += 1
            continue
        if worth < ADMIT_THRESHOLD:
            if event.keep and not event.dupe:
                result.dropped_wrong += 1
            elif event.dupe:
                result.dupes_caught += 1
            else:
                result.kept_right += 1
            continue

        bucket = "workspace"
        if event.keep:
            scope_response = client.ask(
                {"workspace_path": WORKSPACE_PATH, "candidate_note": event.text},
                {"bucket": primitives.choice(SCOPE_QUESTION, SCOPE_CRITERIA)},
            )
            result.tokens += scope_response.input_tokens
            result.latency_ms += scope_response.latency_ms
            bucket = scope_response.choice("bucket").choice
            if bucket == "discard":
                if event.dupe:
                    result.dupes_caught += 1
                else:
                    result.dropped_wrong += 1
                continue
            # The criteria key is `this_folder`; the labels say `workspace`.
            bucket = "workspace" if bucket == "this_folder" else bucket
            if bucket == event.scope:
                result.scope_right += 1
            else:
                result.scope_wrong += 1
                key = f"{event.scope}->{bucket}"
                result.scope_confusions[key] = result.scope_confusions.get(key, 0) + 1

        if not event.keep:
            result.noise_slipped += 1
        elif event.dupe:
            result.duplicates_stored += 1
        admitted.append(event)
        store_texts.append(event.text)
        result.stored += 1

    return admitted, result, store_texts


def run_today() -> tuple[list[Event], Result, list[str]]:
    """No gate, no dedup, everything global."""
    result = Result("today")
    texts = [e.text for e in EVENTS]
    result.stored = len(EVENTS)
    result.duplicates_stored = sum(1 for e in EVENTS if e.dupe)
    return list(EVENTS), result, texts


def run_queries(
    arm: str,
    store: list[str],
    result: Result,
    key: str,
    client: transports.Client | None,
) -> None:
    vectors = cached(store, key, f"store:{arm}")
    qvecs = cached([q["q"] for q in QUERIES], key, "query")
    for case, qvec in zip(QUERIES, qvecs):
        hits = retrieve(store, vectors, case["q"], qvec, SHORTLIST)
        top = hits[0] if hits else None
        result.queries += 1
        if top is not None and store[top] == case["gold"]:
            result.top1 += 1
        if case["gold"] in [store[i] for i in hits]:
            result.in_top10 += 1
        if client is not None and hits:
            shortlist = [store[i] for i in hits]
            response = client.ask(
                {"workspace_path": WORKSPACE_PATH, "query": case["q"]},
                {
                    f"cand::{i}": primitives.noul(
                        f"{RERANK_QUESTION}\n\nChunk (scope: {'workspace' if i < len(store) else 'global'}): {text}",
                        true=RERANK_TRUE,
                        false=RERANK_FALSE,
                    )
                    for i, text in enumerate(shortlist)
                },
            )
            result.tokens += response.input_tokens
            result.latency_ms += response.latency_ms
            scored = sorted(
                ((response.noul(f"cand::{i}"), text) for i, text in enumerate(shortlist)),
                key=lambda kv: -kv[0],
            )
            top = scored[0][1] if scored else None
            if top == case["gold"]:
                result.top1 += 0  # recomputed below
        result.detail.append({"q": case["q"], "gold": case["gold"], "kind": case["kind"], "base_top1": store[top] if top is not None else None})


def rerank_arm(store: list[str], result: Result, key: str, client: transports.Client) -> None:
    """Recompute top-1 with the rerank applied, and count pollution."""
    vectors = cached(store, key, f"store:{result.arm}")
    qvecs = cached([q["q"] for q in QUERIES], key, "query")
    result.top1 = 0
    result.pollution = 0
    for case, qvec in zip(QUERIES, qvecs):
        hits = retrieve(store, vectors, case["q"], qvec, SHORTLIST)
        shortlist = [store[i] for i in hits]
        response = client.ask(
            {"workspace_path": WORKSPACE_PATH, "query": case["q"]},
            {
                f"cand::{i}": primitives.noul(
                    f"{RERANK_QUESTION}\n\nChunk: {text}",
                    true=RERANK_TRUE,
                    false=RERANK_FALSE,
                )
                for i, text in enumerate(shortlist)
            },
        )
        result.tokens += response.input_tokens
        result.latency_ms += response.latency_ms
        scored = sorted(((response.noul(f"cand::{i}"), t) for i, t in enumerate(shortlist)), key=lambda kv: -kv[0])
        top = scored[0][1] if scored else None
        if top == case["gold"]:
            result.top1 += 1
        match = next((e for e in EVENTS if e.text == top), None)
        if case["kind"] == "local" and match is not None:
            if match.project != "grok-build" or not match.keep:
                result.pollution += 1


def report(results: list[Result]) -> None:
    table = Table(title="memory pipeline, end to end — 48 events, 12 later queries")
    for column in ("metric", *[r.arm for r in results]):
        table.add_column(column, justify="right" if column != "metric" else "left")
    rows = [
        ("notes stored", lambda r: f"{r.stored}"),
        ("noise correctly dropped", lambda r: f"{r.kept_right}"),
        ("valuable dropped (loss)", lambda r: f"{r.dropped_wrong}"),
        ("duplicate restatements stored", lambda r: f"{r.duplicates_stored}"),
        ("scope routed right", lambda r: f"{r.scope_right}"),
        ("scope routed wrong", lambda r: f"{r.scope_wrong} {r.scope_confusions or ''}"),
        ("valuable notes lost", lambda r: f"{r.dropped_wrong}"),
        ("duplicates correctly not re-stored", lambda r: f"{r.dupes_caught}"),
        ("noise that slipped through", lambda r: f"{r.noise_slipped}"),
        ("query top-1 (no rerank)", lambda r: f"{r.top1_no_rerank}/{r.queries}"),
        ("query top-1 (reranked)", lambda r: f"{r.top1}/{r.queries}"),
        ("gold in top-10", lambda r: f"{r.in_top10}/{r.queries}"),
        ("cross-project pollution", lambda r: f"{r.pollution}/{r.queries}"),
        ("tokens", lambda r: f"{r.tokens:,}"),
    ]
    for name, getter in rows:
        table.add_row(name, *[getter(r) for r in results])
    console.print(table)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--transport", default="native")
    args = parser.parse_args()
    OUT.mkdir(exist_ok=True)
    key = embed_key()

    started = time.time()
    with transports.Client.build(args.transport, timeout_s=60.0) as client:
        today_events, today, today_store = run_today()
        jev_events, jev, jev_store = run_jev_stages(client)

        # baseline retrieval for both arms, no rerank
        for arm, store, result in (("today", today_store, today), ("today + jev", jev_store, jev)):
            vectors = cached(store, key, f"store:{arm}")
            qvecs = cached([q["q"] for q in QUERIES], key, "query")
            result.top1 = 0
            result.in_top10 = 0
            for case, qvec in zip(QUERIES, qvecs):
                hits = retrieve(store, vectors, case["q"], qvec, SHORTLIST)
                if hits and store[hits[0]] == case["gold"]:
                    result.top1 += 1
                if case["gold"] in [store[i] for i in hits]:
                    result.in_top10 += 1
            result.top1_no_rerank = result.top1
            result.queries = len(QUERIES)

        rerank_arm(today_store, today, key, client)
        rerank_arm(jev_store, jev, key, client)

    today.arm = "today"
    jev.arm = "today + jev"
    report([today, jev])

    console.print(f"\n  wall {time.time() - started:.0f}s, jev tokens {jev.tokens:,}, "
                  f"${jev.tokens / 1e6 * PRICE_IN:.4f}")
    raw = OUT / "results-memory-pipeline.jsonl"
    with raw.open("w", encoding="utf-8") as handle:
        for result in (today, jev):
            handle.write(json.dumps(asdict(result), ensure_ascii=False) + "\n")
    console.print(f"  -> {raw.relative_to(ROOT)}")


if __name__ == "__main__":
    main()